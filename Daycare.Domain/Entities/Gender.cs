/// Represents a child's gender.
/// </summary>
public enum Gender
{
    /// <summary>
    /// Male gender.
    /// </summary>
    Male = 1,

    /// <summary>
    /// Female gender.
    /// </summary>
    Female = 2,

    /// <summary>
    /// Other gender identity.
    /// </summary>
    Other = 3,

    /// <summary>
    /// Prefer not to say.
    /// </summary>
    PreferNotToSay = 4
}
